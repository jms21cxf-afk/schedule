/** 해당 날짜 공휴일 이름 — 없으면 null */
export function getKoreanHoliday(
  year: number,
  month: number,
  day: number
): string | null {
  const key = toDateString(year, month, day);
  return HOLIDAYS_BY_YEAR[year]?.[key] ?? null;
}

export function isKoreanHoliday(year: number, month: number, day: number): boolean {
  return getKoreanHoliday(year, month, day) !== null;
}
